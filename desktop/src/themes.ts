export function getThemeSpec(id: ReadingThemeId): LumaThemeSpec {
  return LUMA_THEMES.find((t) => t.id === id) ?? LUMA_THEMES[0];
}

export function applyThemeToDocument(themeId: ReadingThemeId) {
  const t = getThemeSpec(themeId);
  const root = document.documentElement;
  root.style.setProperty('--luma-bg', t.bg);
  root.style.setProperty('--luma-surface', t.surface);
  root.style.setProperty('--luma-surface-alt', t.surfaceAlt);
  root.style.setProperty('--luma-sidebar', t.sidebar);
  root.style.setProperty('--luma-ink', t.ink);
  root.style.setProperty('--luma-ink-muted', t.inkMuted);
  root.style.setProperty('--luma-accent', t.accent);
  root.style.setProperty('--luma-accent-soft', t.accentSoft);
  root.style.setProperty('--luma-on-accent', t.onAccent);
  root.style.setProperty('--luma-border', t.border);
  root.style.setProperty('--luma-shadow', t.shadow);
  root.dataset.lumaTheme = t.id;
  root.dataset.lumaMode = t.isDark ? 'dark' : 'light';
}
